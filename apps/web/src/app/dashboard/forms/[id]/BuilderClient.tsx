"use client";

import {
  useCallback,
  useEffect,
  useReducer,
  useRef,
  useState,
  type DragEvent,
} from "react";
import { t } from "@form/i18n";
import { MAX_BLOCKS, validateDraftSchema } from "@form/form-schema";
import type { FormBlock, FormDraftSchema } from "@form/contracts";
import { generateBlockId } from "../../../../lib/builder-id";
import { describeIssues } from "../../../../lib/builder-issues";
import {
  builderReducer,
  type BuilderAction,
  type BuilderBlockKind,
} from "../../../../lib/builder-reducer";
import { createDraftSaver, type DraftSaver } from "../../../../lib/builder-save";

/**
 * The dashboard builder (ticket 08) — client component under the T06 shell.
 *
 * Editing: the respondent-facing envelope title (NOT forms.name, which stays
 * on the page above) and the four M0 block kinds (welcome / short_text /
 * long_text / ending) with label/title, description, placeholder and required
 * controls. Block IDs are generated ONCE on add by lib/builder-id.ts and are
 * never regenerated by edit/reorder/delete.
 *
 * Reordering: HTML5 drag on a per-block handle PLUS move-up/move-down buttons
 * — the buttons are the keyboard-accessible path (drag is a progressive
 * bonus; no dependencies).
 *
 * Saving: lib/builder-save.ts serializes autosaves (debounce + one in-flight
 * request, next edit queued behind it) against the last-seen integer
 * `draftVersion`. Client-side validation runs the SHARED schema engine before
 * scheduling (early feedback; the server stays authoritative). A 409
 * `draft_conflict` halts autosaving permanently and swaps the editor for a
 * reload state instead of overwriting the other tab.
 *
 * All strings come from the @form/i18n catalog.
 */

type SaveStatus = "saved" | "saving" | "error" | "conflict";

const STATUS_KEY = {
  saved: "dashboard.builder.status.saved",
  saving: "dashboard.builder.status.saving",
  error: "dashboard.builder.status.error",
} as const;

const ADD_KEY = {
  welcome: "dashboard.builder.add.welcome",
  short_text: "dashboard.builder.add.shortText",
  long_text: "dashboard.builder.add.longText",
  ending: "dashboard.builder.add.ending",
} as const;

export default function BuilderClient(props: {
  formId: string;
  initialSchema: FormDraftSchema;
  initialDraftVersion: number;
}) {
  const [schema, dispatch] = useReducer(builderReducer, props.initialSchema);
  const [status, setStatus] = useState<SaveStatus>("saved");
  const [issues, setIssues] = useState<string[]>([]);

  const [saver] = useState<DraftSaver>(() =>
    createDraftSaver({
      formId: props.formId,
      initialDraftVersion: props.initialDraftVersion,
    }),
  );
  const dirtyRef = useRef(false);
  const conflictRef = useRef(false);
  const outstandingRef = useRef(0);

  /** Every user mutation goes through here (marks the draft dirty). */
  const apply = useCallback(
    (action: BuilderAction) => {
      dirtyRef.current = true;
      dispatch(action);
    },
    [dispatch],
  );

  useEffect(() => {
    // Client-side validation mirrors the shared schema (early feedback only —
    // the server re-validates and stays authoritative via 409/422).
    const result = validateDraftSchema(schema);
    setIssues(result.ok ? [] : describeIssues(result.issues));

    if (!dirtyRef.current || conflictRef.current || !result.ok) return;

    outstandingRef.current++;
    setStatus("saving");
    void saver.schedule(schema).then((outcome) => {
      outstandingRef.current--;
      if (outcome.kind === "conflict") {
        // Another tab saved first: STOP autosaving, offer reload — never
        // overwrite. (The saver is halted too; this belt keeps the UI quiet.)
        conflictRef.current = true;
        setStatus("conflict");
      } else if (outcome.kind === "error") {
        setStatus("error");
      } else if (outcome.kind === "saved") {
        setStatus(outstandingRef.current > 0 ? "saving" : "saved");
      }
      // superseded: a newer save is already queued behind this one.
    });
  }, [schema, saver]);

  const conflict = status === "conflict";

  function addBlock(kind: BuilderBlockKind) {
    // Fresh 12-char URL-safe ID per ADD; never regenerated afterwards.
    const id = generateBlockId(new Set(schema.blocks.map((b) => b.id)));
    apply({ type: "add_block", id, kind });
  }

  return (
    <section aria-label={t("dashboard.builder.editorLabel")}>
      <div role="status">{conflict ? "" : t(STATUS_KEY[status])}</div>

      {conflict ? (
        <div role="alert" style={{ border: "1px solid #b00020", padding: "0.75rem" }}>
          <p>
            <strong>{t("dashboard.builder.status.conflict")}</strong>
          </p>
          <p>{t("dashboard.builder.status.conflictHint")}</p>
          <button type="button" onClick={() => window.location.reload()}>
            {t("dashboard.builder.status.reload")}
          </button>
        </div>
      ) : null}

      <fieldset disabled={conflict} style={{ border: "none", margin: 0, padding: 0 }}>
        <div>
          <label htmlFor="builder-schema-title">
            {t("dashboard.builder.schemaTitleLabel")}
          </label>
          <input
            id="builder-schema-title"
            type="text"
            value={schema.title}
            onChange={(e) => apply({ type: "set_title", title: e.target.value })}
          />
          <p style={{ color: "#555", margin: "0.25rem 0 0" }}>
            {t("dashboard.builder.schemaTitleHint")}
          </p>
        </div>

        <h2>{t("dashboard.builder.addBlockHeading")}</h2>
        <div style={{ display: "flex", gap: 8, flexWrap: "wrap" }}>
          {(["welcome", "short_text", "long_text", "ending"] as const).map((kind) => (
            <button
              key={kind}
              type="button"
              onClick={() => addBlock(kind)}
              disabled={conflict || schema.blocks.length >= MAX_BLOCKS}
            >
              {t(ADD_KEY[kind])}
            </button>
          ))}
        </div>

        <h2>{t("dashboard.forms.blocksHeading")}</h2>
        {schema.blocks.length === 0 ? (
          <p>{t("dashboard.forms.blocksEmpty")}</p>
        ) : (
          <ol style={{ listStyle: "none", padding: 0 }}>
            {schema.blocks.map((block, index) => (
              <li key={block.id}>
                <BlockCard
                  block={block}
                  index={index}
                  total={schema.blocks.length}
                  apply={apply}
                />
              </li>
            ))}
          </ol>
        )}
      </fieldset>

      {issues.length > 0 && !conflict ? (
        <div role="alert">
          <p>{t("dashboard.builder.validationHeading")}</p>
          <ul>
            {issues.map((line, i) => (
              <li key={i}>{line}</li>
            ))}
          </ul>
        </div>
      ) : null}
    </section>
  );
}

function kindName(kind: BuilderBlockKind): string {
  switch (kind) {
    case "welcome":
      return t("dashboard.forms.block.welcome");
    case "short_text":
      return t("dashboard.forms.block.shortText");
    case "long_text":
      return t("dashboard.forms.block.longText");
    case "ending":
      return t("dashboard.forms.block.ending");
  }
}

function BlockCard(props: {
  block: FormBlock;
  index: number;
  total: number;
  apply: (action: BuilderAction) => void;
}) {
  const { block, index, total, apply } = props;
  const name = kindName(block.kind);
  const dragIdRef = useRef<string | null>(null);

  function onDrop(event: DragEvent<HTMLElement>) {
    event.preventDefault();
    const dragged = dragIdRef.current;
    dragIdRef.current = null;
    if (dragged && dragged !== block.id) {
      apply({ type: "move_block_to", id: dragged, index });
    }
  }

  return (
    <div
      onDragOver={(e) => e.preventDefault()}
      onDrop={onDrop}
      style={{ border: "1px solid #eee", padding: "0.75rem", borderRadius: 4 }}
    >
      <p style={{ margin: 0 }}>
        <span style={{ color: "#555" }}>{name}</span>
        <span
          draggable
          onDragStart={() => {
            dragIdRef.current = block.id;
          }}
          onDragEnd={() => {
            dragIdRef.current = null;
          }}
          title={t("dashboard.builder.dragHandle", { name })}
          style={{ cursor: "grab", padding: "0 0.5rem" }}
        >
          ⠿
        </span>
      </p>

      <BlockFields block={block} apply={apply} />

      <div style={{ display: "flex", gap: 8, marginTop: "0.5rem" }}>
        <button
          type="button"
          onClick={() => apply({ type: "move_block", id: block.id, direction: "up" })}
          disabled={index === 0}
          aria-label={t("dashboard.builder.moveUp", { name })}
        >
          ↑
        </button>
        <button
          type="button"
          onClick={() => apply({ type: "move_block", id: block.id, direction: "down" })}
          disabled={index === total - 1}
          aria-label={t("dashboard.builder.moveDown", { name })}
        >
          ↓
        </button>
        <button
          type="button"
          onClick={() => apply({ type: "remove_block", id: block.id })}
          aria-label={t("dashboard.builder.deleteBlock", { name })}
        >
          ✕
        </button>
      </div>
    </div>
  );
}

function BlockFields(props: {
  block: FormBlock;
  apply: (action: BuilderAction) => void;
}) {
  const { block, apply } = props;

  if (block.kind === "welcome" || block.kind === "ending") {
    return (
      <div>
        <div>
          <label htmlFor={`${block.id}-title`}>{t("dashboard.builder.titleLabel")}</label>
          <input
            id={`${block.id}-title`}
            type="text"
            value={block.title}
            onChange={(e) =>
              apply({ type: "update_block", id: block.id, patch: { title: e.target.value } })
            }
          />
        </div>
        <div>
          <label htmlFor={`${block.id}-description`}>
            {t("dashboard.builder.descriptionLabel")}
          </label>
          <input
            id={`${block.id}-description`}
            type="text"
            value={block.description ?? ""}
            onChange={(e) =>
              apply({
                type: "update_block",
                id: block.id,
                patch: { description: e.target.value },
              })
            }
          />
        </div>
      </div>
    );
  }

  return (
    <div>
      <div>
        <label htmlFor={`${block.id}-label`}>{t("dashboard.builder.labelLabel")}</label>
        <input
          id={`${block.id}-label`}
          type="text"
          value={block.label}
          onChange={(e) =>
            apply({ type: "update_block", id: block.id, patch: { label: e.target.value } })
          }
        />
      </div>
      <div>
        <label htmlFor={`${block.id}-description`}>
          {t("dashboard.builder.descriptionLabel")}
        </label>
        <input
          id={`${block.id}-description`}
          type="text"
          value={block.description ?? ""}
          onChange={(e) =>
            apply({
              type: "update_block",
              id: block.id,
              patch: { description: e.target.value },
            })
          }
        />
      </div>
      <div>
        <label htmlFor={`${block.id}-placeholder`}>
          {t("dashboard.builder.placeholderLabel")}
        </label>
        <input
          id={`${block.id}-placeholder`}
          type="text"
          value={block.placeholder ?? ""}
          onChange={(e) =>
            apply({
              type: "update_block",
              id: block.id,
              patch: { placeholder: e.target.value },
            })
          }
        />
      </div>
      <label style={{ display: "inline-flex", gap: 6, alignItems: "center" }}>
        <input
          type="checkbox"
          checked={block.required}
          onChange={(e) =>
            apply({
              type: "update_block",
              id: block.id,
              patch: { required: e.target.checked },
            })
          }
        />
        {t("dashboard.builder.requiredLabel")}
      </label>
    </div>
  );
}