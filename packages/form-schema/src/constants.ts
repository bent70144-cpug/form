/**
 * Concrete limits for the form-schema package (spec: "Form schema and
 * versioning"). These values are part of the public contract — error codes and
 * limit numbers must stay stable across releases.
 *
 * Character limits count UTF-16 code units (`string.length`), matching how the
 * builder and API enforce them; JSON caps count UTF-8 bytes via `TextEncoder`.
 */

/** Form title: 200 characters. */
export const TITLE_MAX = 200;
/** Block label or title (welcome/ending): 500 characters. */
export const LABEL_MAX = 500;
/** Block description: 2,000 characters. */
export const DESCRIPTION_MAX = 2000;
/** Question placeholder: 200 characters. */
export const PLACEHOLDER_MAX = 200;
/** Maximum number of blocks per form. */
export const MAX_BLOCKS = 200;
/** Draft schema JSON cap: 256 KB, counted in bytes. */
export const DRAFT_JSON_MAX_BYTES = 256 * 1024;
/** Submission payload JSON cap: 100 KB, counted in bytes. */
export const SUBMISSION_JSON_MAX_BYTES = 100 * 1024;
/** Short-text answer: 1,000 characters. */
export const SHORT_TEXT_ANSWER_MAX = 1000;
/** Long-text answer: 10,000 characters. */
export const LONG_TEXT_ANSWER_MAX = 10000;

/**
 * Block IDs are 12-character URL-safe nanoids generated by the client; the
 * server enforces this format and uniqueness within the form.
 */
export const BLOCK_ID_RE = /^[A-Za-z0-9_-]{10,32}$/;

/** NUL is rejected everywhere because Postgres JSONB cannot store it. */
export const NUL = "\u0000";

/** The M0 block kinds (the block union of the stable envelope). */
export const BLOCK_KINDS = ["welcome", "short_text", "long_text", "ending"] as const;
